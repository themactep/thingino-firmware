#!/bin/sh
# Add this camera's buttons from its thingino.json to the mainline kernel's
# built-in device tree. The pins are board-specific while the tree is per-SoC,
# so the keys are generated into this build's copy of it, in an include that
# the tree gets appended once.
#
# Key codes match thingino-button.conf: gpio.button_reset is KEY_ENTER,
# gpio.chime is KEY_1. Buttons pull the pin to ground against a pull-up, so
# they are active-low, and the pin gets bias-pull-up through the pin
# controller (the GPIO cell takes no bias flag on these SoCs). The node's
# label names the input device "gpio-keys", which thingino-button
# auto-detects.
#
# gpio.pir is a PIR motion sensor's output, reported as KEY_F13 as the
# vendor kernels do (their SDK's sample-pir and SU_Key_EnableEvent expect
# it, and it can be disabled through gpio-keys' disabled_keys). The sensor
# drives the line, high on motion: a bare pin is active-high, an object
# {"pin": N, "active_low": true} states the other polarity. It gets no pull.
#
# Usage: inject-button-dt-mainline.sh <thingino.json> <linux-dir>
set -e

JSON="$1"
LINUX="$2"
[ -f "$LINUX/.config" ] || exit 0

name=$(sed -n 's/^CONFIG_BUILTIN_DTB_NAME="\(.*\)"$/\1/p' "$LINUX/.config")
[ -n "$name" ] || exit 0
dts="$LINUX/arch/mips/boot/dts/$name.dts"
[ -f "$dts" ] || exit 0

inc="$(basename "$name")-thingino-buttons.dtsi"
tmp="$(dirname "$dts")/$inc.tmp"

python3 - "$JSON" >"$tmp" <<'PY'
import json, os, sys

conf = sys.argv[1]
keys = []  # (name, code, pin, active_low, pull_up, can_disable)
if os.path.isfile(conf):
    g = json.load(open(conf)).get("gpio", {})
    for name, key, code in (("reset", "button_reset", 28), ("chime", "chime", 2)):
        v = g.get(key)
        pin = v.get("pin") if isinstance(v, dict) else v
        if isinstance(pin, int) and not isinstance(pin, bool) and 0 <= pin < 192:
            keys.append((name, code, pin, True, True, False))
    v = g.get("pir")
    pin = v.get("pin") if isinstance(v, dict) else v
    al = isinstance(v, dict) and v.get("active_low") is True
    if isinstance(pin, int) and not isinstance(pin, bool) and 0 <= pin < 192:
        keys.append(("pir", 183, pin, al, False, True))

pulled = [k for k in keys if k[4]]
print("/* Generated by thingino-button from thingino.json. */")
if keys:
    print("\n/ {\n\tgpio-keys {\n\t\tcompatible = \"gpio-keys\";\n\t\tlabel = \"gpio-keys\";")
    if pulled:
        print("\t\tpinctrl-names = \"default\";\n\t\tpinctrl-0 = %s;"
              % ", ".join("<&pins_button_%s>" % k[0] for k in pulled))
    for name, code, pin, al, pu, cd in keys:
        print("\n\t\tbutton-%s {\n\t\t\tlabel = \"%s\";\n\t\t\tlinux,code = <%d>;\n"
              "\t\t\tgpios = <&gp%s %d %d>;\t/* %s */%s\n\t\t};"
              % (name, name, code, "abcdef"[pin // 32], pin % 32, 1 if al else 0,
                 "GPIO_ACTIVE_LOW" if al else "GPIO_ACTIVE_HIGH",
                 "\n\t\t\tlinux,can-disable;" if cd else ""))
    print("\t};\n};")
    if pulled:
        print("\n&pinctrl {")
        for name, code, pin, al, pu, cd in pulled:
            print("\tpins_button_%s: button-%s {\n\t\tpins = \"P%s%d\";\n\t\tbias-pull-up;\n\t};"
                  % (name, name, "ABCDEF"[pin // 32], pin % 32))
        print("};")
print("thingino-button: %s buttons: %s"
      % (os.path.basename(conf), " ".join("%s=gpio%d" % (k[0], k[2]) for k in keys) or "none"),
      file=sys.stderr)
PY

# Rewritten only on change, so an unchanged board does not rebuild the dtb.
if cmp -s "$tmp" "$(dirname "$dts")/$inc"; then
	rm -f "$tmp"
else
	mv "$tmp" "$(dirname "$dts")/$inc"
fi
grep -q "#include \"$inc\"" "$dts" || printf '\n#include "%s"\n' "$inc" >>"$dts"
exit 0
